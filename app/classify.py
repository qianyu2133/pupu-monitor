def _hit(name, words):
    return any(w in name for w in words)


def classify(name):
    """返回 '肉类' / '海鲜' / '其它'。

    先把容易误伤的专有名词（牛油果、牛奶、五羊、鱼香…）从标题里剔掉，
    再判断剩下的部分——这样"牦牛肉丸""鱼香肉丝"不会被误排除。
    """
    if not name:
        return "其它"
    n = str(name)
    for w in WHITELIST_OTHER:
        n = n.replace(w, "")
    if _hit(n, SEAFOOD):
        return "海鲜"
    if _hit(n, MEAT):
        return "肉类"
    return "其它"
